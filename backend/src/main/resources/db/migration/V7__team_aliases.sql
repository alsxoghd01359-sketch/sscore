    PRIMARY KEY (id),
    UNIQUE KEY uq_team_aliases (team_id, name),
    KEY idx_team_aliases_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

